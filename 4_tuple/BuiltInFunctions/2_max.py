# max() is a Built-in function in tuple
# Used : To get the maximum value from the tuple
# Syntax : max(tuple)
# Returns : Maximum value from the tuple

tuple = (1,2,3,4,34,4,34,5,True)
# Gives error if "","string"

max = max(tuple)
print(f"maximum value in tuple : {max}")

# Output:
# maximum value in tuple : 34
