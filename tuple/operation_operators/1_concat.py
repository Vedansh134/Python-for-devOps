# concatenation is ued to join two or more tuples together
# It is represented by the + symbol.
# Syntax : tuple1 + tuple2
# where tuple1 and tuple2 are the tuples to be concatenated.

tuple1 = ("Frontend","Backend","Fullstack","DevOps","Data Engineer","Data Scientist")
tuple2 = ("AI Engineer","ML Engineer","Cloud Engineer","Security Engineer")

# using + operator to concatenate two tuples
result_tuple = tuple1 + tuple2

print(f"Concatenated tuple is : {result_tuple}")

# output :
# Concatenated tuple is : ('Frontend', 'Backend', 'Fullstack', 'DevOps', 'Data Engineer', 'Data Scientist', 'AI Engineer', 'ML Engineer', 'Cloud Engineer', 'Security Engineer')

