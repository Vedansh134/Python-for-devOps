# min() is a Built-in function in tuple
# Used : To get the minimum value from the tuple
# Syntax : min(tuple)
# Returns : Minimum value from the tuple

tuple = (1,2,3,4,34,4,34,5,True)
# Gives error if "","string"

min = min(tuple)
print(f"Minimum value in tuple : {min}")

# output :
# Minimum value in tuple : 1