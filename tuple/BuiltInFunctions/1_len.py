# len() is a Built-in function in tuple
# Used : To get the length of the tuple
# Syntax : len(tuple)
# Returns : Integer value

tuple = (2,4,6,8,(1,3,5,7),10,True,""," ","string",0,10)

length = len(tuple)
print(f"Length of the tuple : {length}")
print(type(length))

# Output:
# Length of the tuple : 13
# <class 'int'>